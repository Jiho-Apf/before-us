export function validateRelationshipPreferences(
  values: Record<string, string | string[] | boolean>,
) {
  const errors: Record<string, string> = {}
  const mbti = values[`${RELATIONSHIP_PREFIX}mbti`]
  if (Array.isArray(mbti) && mbti.includes("상관없어요") && mbti.length > 1)
    errors[`${RELATIONSHIP_PREFIX}mbti`] =
      "상관없어요와 특정 MBTI는 함께 선택할 수 없어요."
  return errors
}
