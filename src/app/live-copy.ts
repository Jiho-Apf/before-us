import { LIVE } from "./backend/client"

// 실제 서버 모드에서 신청서 항목의 데모 표기(가상·데모)를 걷어 낸다. 데모 모드에서는 문장을 그대로 둔다.
const RULES: [RegExp, string][] = [
  [/\s*\(선택·데모\)/g, " (선택)"],
  [/\s*\(데모\)/g, ""],
  [/\s*\(가상[^)]*\)/g, ""],
  [/\s*·\s*가상 정보만/g, ""],
  [/\s*·\s*실제 (?:수집|발송) 없음/g, ""],
  [/가상구 · 가상 시·군·구만 입력해 주세요/g, "예: 마포구 · 시·군·구까지만 적어 주세요"],
  [/가상 활동용 이름/g, "소개에서 쓸 이름"],
  [/가상 인물에 대한 소개를/g, "나에 대한 소개를"],
  [/가상 인물의/g, "나의"],
  [/가상 답변을/g, "답변을"],
  [/\s*가상 내용만 입력해 주세요\./g, ""],
  [/유효한 가상 생년월일/g, "올바른 생년월일"],
  [/동일 가상 파일이/g, "같은 사진이"],
  [/가상 파일을 선택해 주세요\./g, "사진을 골라 주세요."],
]
export const copy = (text: string) => (LIVE ? RULES.reduce((value, [pattern, next]) => value.replace(pattern, next), text) : text)
